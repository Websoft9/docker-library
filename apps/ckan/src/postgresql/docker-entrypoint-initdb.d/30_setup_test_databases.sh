#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" <<-EOSQL
    CREATE DATABASE ckan_test OWNER "$CKAN_POSTGRES_USER" ENCODING 'utf-8';
    CREATE DATABASE datastore_test OWNER "$CKAN_DATASTORE_POSTGRES_WRITE_USER" ENCODING 'utf-8';
    GRANT CONNECT ON DATABASE datastore_test TO "$CKAN_DATASTORE_POSTGRES_READ_USER";
EOSQL
