#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$CKAN_DATASTORE_POSTGRES_DB" <<-EOSQL
    GRANT ALL PRIVILEGES ON DATABASE "$CKAN_DATASTORE_POSTGRES_DB" TO "$CKAN_DATASTORE_POSTGRES_WRITE_USER";
    GRANT CONNECT ON DATABASE "$CKAN_DATASTORE_POSTGRES_DB" TO "$CKAN_DATASTORE_POSTGRES_READ_USER";
EOSQL
