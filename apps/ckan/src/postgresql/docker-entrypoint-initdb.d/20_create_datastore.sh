#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" <<-EOSQL
    CREATE ROLE "$CKAN_DATASTORE_POSTGRES_READ_USER" NOSUPERUSER NOCREATEDB NOCREATEROLE LOGIN PASSWORD '$CKAN_DATASTORE_POSTGRES_READ_PWD';
    CREATE ROLE "$CKAN_DATASTORE_POSTGRES_WRITE_USER" NOSUPERUSER NOCREATEDB NOCREATEROLE LOGIN PASSWORD '$CKAN_DATASTORE_POSTGRES_WRITE_PWD';
    CREATE DATABASE "$CKAN_DATASTORE_POSTGRES_DB" OWNER "$CKAN_DATASTORE_POSTGRES_WRITE_USER" ENCODING 'utf-8';
EOSQL
