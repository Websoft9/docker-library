#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Iterable, NamedTuple


COMMAND_ID_RE = re.compile(r"^libs-[a-z0-9-]+$")
REPO_ROOT = Path(__file__).resolve().parents[2]
MANIFEST_PATH = REPO_ROOT / "skills" / "commands.manifest.json"


class CommandSpec(NamedTuple):
    command_id: str
    description: str
    skill: str
    argument_hint: str
    usage: str


def load_specs(path: Path) -> list[CommandSpec]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    items = payload.get("commands")
    if not isinstance(items, list) or not items:
        raise ValueError("commands manifest must contain a non-empty 'commands' array")

    specs: list[CommandSpec] = []
    seen_ids: set[str] = set()
    for idx, item in enumerate(items):
        if not isinstance(item, dict):
            raise ValueError(f"commands[{idx}] must be an object")
        command_id = _require_string(item, "id", idx)
        description = _require_string(item, "description", idx)
        skill = _require_string(item, "skill", idx)
        argument_hint = _require_string(item, "argument_hint", idx)
        usage = _require_string(item, "usage", idx)

        if not COMMAND_ID_RE.match(command_id):
            raise ValueError(f"commands[{idx}].id must match {COMMAND_ID_RE.pattern}")
        if command_id in seen_ids:
            raise ValueError(f"duplicate command id: {command_id}")
        seen_ids.add(command_id)

        specs.append(
            CommandSpec(
                command_id=command_id,
                description=description,
                skill=skill,
                argument_hint=argument_hint,
                usage=usage,
            )
        )
    return specs


def _require_string(item: dict, key: str, idx: int) -> str:
    value = item.get(key)
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"commands[{idx}].{key} must be a non-empty string")
    return value.strip()


def render_opencode(spec: CommandSpec) -> str:
    return (
        "---\n"
        f"description: {spec.description}\n"
        "agent: build\n"
        f"argument-hint: {spec.argument_hint}\n"
        "---\n\n"
        "<!-- generated by ci/scripts/build_ai_commands.py; do not edit directly -->\n\n"
        f"Use the `{spec.skill}` skill.\n\n"
        f"Usage: {spec.usage}\n\n"
        "If input is empty or `help`, return usage and ask for required arguments.\n\n"
        "$ARGUMENTS\n"
    )


def render_prompt(spec: CommandSpec, skill_link: str) -> str:
    return (
        "---\n"
        f"name: {spec.command_id}\n"
        f'description: "Route to {spec.skill} skill."\n'
        f"argument-hint: \"{spec.argument_hint}\"\n"
        "agent: agent\n"
        "---\n\n"
        "<!-- generated by ci/scripts/build_ai_commands.py; do not edit directly -->\n\n"
        f"Use [{spec.skill}]({skill_link}).\n\n"
        f"Usage: `{spec.usage}`\n\n"
        "If input is empty or `help`, return usage and ask for required arguments.\n"
    )


def expected_outputs(repo_root: Path, specs: Iterable[CommandSpec]) -> dict[Path, str]:
    outputs: dict[Path, str] = {}
    for spec in specs:
        outputs[repo_root / ".opencode" / "command" / f"{spec.command_id}.md"] = render_opencode(spec)
        outputs[repo_root / ".github" / "prompts" / f"{spec.command_id}.prompt.md"] = render_prompt(
            spec, "../../skills/" + spec.skill + "/SKILL.md"
        )
        outputs[repo_root / ".codex" / "prompts" / f"{spec.command_id}.prompt.md"] = render_prompt(
            spec, "../../skills/" + spec.skill + "/SKILL.md"
        )
    return outputs


def find_stale_outputs(repo_root: Path, expected: dict[Path, str]) -> list[Path]:
    candidates: list[Path] = []
    candidates.extend((repo_root / ".opencode" / "command").glob("libs-*.md"))
    candidates.extend((repo_root / ".github" / "prompts").glob("libs-*.prompt.md"))
    candidates.extend((repo_root / ".codex" / "prompts").glob("libs-*.prompt.md"))
    stale = [path for path in candidates if path not in expected]
    return sorted(stale, key=lambda path: str(path))


def find_outdated_outputs(expected: dict[Path, str]) -> list[Path]:
    outdated: list[Path] = []
    for path, content in sorted(expected.items(), key=lambda item: str(item[0])):
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            outdated.append(path)
    return outdated


def write_outputs(outputs: dict[Path, str]) -> list[Path]:
    changed: list[Path] = []
    for path, content in sorted(outputs.items(), key=lambda item: str(item[0])):
        path.parent.mkdir(parents=True, exist_ok=True)
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            path.write_text(content, encoding="utf-8")
            changed.append(path)
    return changed


def remove_stale_outputs(paths: Iterable[Path]) -> list[Path]:
    removed: list[Path] = []
    for path in paths:
        if path.exists():
            path.unlink()
            removed.append(path)
    return removed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate AI command adapters from manifest")
    parser.add_argument("--check", action="store_true", help="exit non-zero if outputs are not up-to-date")
    parser.add_argument("--clean", action="store_true", help="remove stale generated adapter files")
    args = parser.parse_args(argv)

    specs = load_specs(MANIFEST_PATH)
    outputs = expected_outputs(REPO_ROOT, specs)
    stale = find_stale_outputs(REPO_ROOT, outputs)

    if args.check:
        outdated = find_outdated_outputs(outputs)
        if outdated or stale:
            for path in outdated:
                print(f"outdated: {path.relative_to(REPO_ROOT)}")
            for path in stale:
                print(f"stale: {path.relative_to(REPO_ROOT)}")
            return 1
        print(f"verified {len(outputs)} adapter files from {len(specs)} command specs")
        return 0

    changed = write_outputs(outputs)
    removed = remove_stale_outputs(stale) if args.clean else []

    print(f"built {len(outputs)} adapter files from {len(specs)} command specs")
    if changed:
        print(f"updated {len(changed)} files")
    if removed:
        print(f"removed {len(removed)} stale files")
    elif stale and not args.clean:
        print(f"found {len(stale)} stale files (run with --clean to remove)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
